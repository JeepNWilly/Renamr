<#
.SYNOPSIS  Builds the single-file app from source:
           1) ..\Renamr.ps1  = Renamr.Gui.ps1 with Renamr.Engine.ps1 embedded (Base64)
           2) ..\Renamr.exe  = (1) compiled with PS2EXE (Windows only; installs ps2exe for the current user if missing)
.EXAMPLE   powershell -ExecutionPolicy Bypass -File .\build_exe.ps1            # build ps1 + exe
.EXAMPLE   powershell -ExecutionPolicy Bypass -File .\build_exe.ps1 -NoCompile # only regenerate Renamr.ps1
#>
param([switch]$NoCompile, [string]$OutDir = (Split-Path -Parent $PSScriptRoot))
$ErrorActionPreference = 'Stop'
$gui = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'Renamr.Gui.ps1'))
$eng = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'Renamr.Engine.ps1'))
$marker = '$PR_EMBEDDED_ENGINE = $null  #@@ENGINE@@'
if (-not $gui.Contains($marker)) { throw "Marker not found in Renamr.Gui.ps1: $marker" }
# version: source\VERSION (major.minor.patch) + build number from source\BUILD_NUMBER (incremented on every exe compile)
$verFile = Join-Path $PSScriptRoot 'VERSION'; $bnFile = Join-Path $PSScriptRoot 'BUILD_NUMBER'
$ver = ([IO.File]::ReadAllText($verFile)).Trim()
if ($ver -notmatch '^\d+\.\d+\.\d+$') { throw "VERSION must look like 1.2.3 (got '$ver')" }
$bn = 0; if (Test-Path -LiteralPath $bnFile) { [int]::TryParse(([IO.File]::ReadAllText($bnFile)).Trim(), [ref]$bn) | Out-Null }
if (-not $NoCompile) { $bn++; [IO.File]::WriteAllText($bnFile, "$bn`r`n") }
$AppVersion = "$ver.$bn"
$vmarker = "`$AppVersion = 'dev'  #@@VERSION@@"
if (-not $gui.Contains($vmarker)) { throw "Marker not found in Renamr.Gui.ps1: $vmarker" }
$gui = $gui.Replace($vmarker, "`$AppVersion = '$AppVersion'")
$b64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($eng))
$line = '$PR_EMBEDDED_ENGINE = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String(''' + $b64 + '''))'
$combined = "# GENERATED by source\build_exe.ps1 - edit source\Renamr.Gui.ps1 / Renamr.Engine.ps1 instead.`r`n" + $gui.Replace($marker, $line)
$ps1 = Join-Path $OutDir 'Renamr.ps1'
[IO.File]::WriteAllText($ps1, $combined, (New-Object Text.UTF8Encoding($true)))
Write-Host "Wrote $ps1 (version $AppVersion)"
$ico0 = Join-Path $PSScriptRoot 'Renamr.ico'
if (Test-Path -LiteralPath $ico0) { Copy-Item -LiteralPath $ico0 -Destination (Join-Path $OutDir 'Renamr.ico') -Force }
if ($NoCompile) { return }
if (-not (Get-Module -ListAvailable -Name ps2exe)) {
    Write-Host 'Installing ps2exe module for the current user...'
    if (-not (Get-PackageProvider -ListAvailable -Name NuGet -ErrorAction SilentlyContinue)) { Install-PackageProvider -Name NuGet -Scope CurrentUser -Force | Out-Null }
    Install-Module ps2exe -Scope CurrentUser -Force
}
Import-Module ps2exe
$exe = Join-Path $OutDir 'Renamr.exe'
$icon = Join-Path $PSScriptRoot 'Renamr.ico'
$iconArgs = @{}
if (Test-Path -LiteralPath $icon) {
    $iconArgs['iconFile'] = $icon
    Copy-Item -LiteralPath $icon -Destination (Join-Path $OutDir 'Renamr.ico') -Force   # GUI window icon for the .ps1/.cmd launch
}
Invoke-ps2exe @iconArgs -inputFile $ps1 -outputFile $exe -noConsole -STA -title 'Renamr' -product 'Renamr' -version $AppVersion -description "Renamr $AppVersion - renames movie/TV files to Plex naming using TMDB"
Write-Host "Built $exe (version $AppVersion)"
